def get_program(program_id):
    for program in st.session_state.data["programs"]:
        if program["id"] == program_id:
            return program
    return None


def get_subprogram(program_id, subprogram_id):
    program = get_program(program_id)

    if not program:
        return None

    for sub in program.get("subPrograms", []):
        if sub["id"] == subprogram_id:
            return sub

    return None


def find_module(parent, module_id):
    for mod in parent.get("modules", []):
        if mod["id"] == module_id:
            return mod
    return None


def make_id(prefix):
    return prefix + "_" + datetime.now().strftime("%Y%m%d%H%M%S%f")


