def add_recipe_form(mod):

    if not st.session_state.admin:
        return

    with st.expander(
        "➕ إضافة بطاقة تقنية / وصفة"
    ):

        with st.form(
            "new_recipe_" + str(mod["id"])
        ):

            title = st.text_input(
                "اسم الوصفة"
            )

            category = st.text_input(
                "التصنيف"
            )

            objective = st.text_area(
                "الهدف المهني"
            )

            ingredients_text = st.text_area(
                "المقادير\nاكتب كل مقدار في سطر بالشكل:\nلوز | 500 | غ"
            )

            steps_text = st.text_area(
                "مراحل الإنجاز — كل مرحلة في سطر"
            )

            equipment_text = st.text_area(
                "العتاد — كل أداة في سطر"
            )

            safety_text = st.text_area(
                "قواعد السلامة — كل قاعدة في سطر"
            )

            evaluation_text = st.text_area(
                "معايير التقييم — كل معيار في سطر"
            )

            submit = st.form_submit_button(
                "حفظ البطاقة التقنية"
            )

            if submit:

                if not title.strip():

                    st.error(
                        "أدخل اسم الوصفة."
                    )

                else:

                    ingredients = []

                    for line in ingredients_text.split("\n"):

                        parts = [
                            x.strip()
                            for x in line.split("|")
                        ]

                        if len(parts) == 3:

                            try:
                                amount = float(parts[1])
                                ingredients.append(
                                    (
                                        parts[0],
                                        amount,
                                        parts[2]
                                    )
                                )
                            except:
                                pass

                    steps = [
                        x.strip()
                        for x in steps_text.split("\n")
                        if x.strip()
                    ]

                    equipment = [
                        x.strip()
                        for x in equipment_text.split("\n")
                        if x.strip()
                    ]

                    safety = [
                        x.strip()
                        for x in safety_text.split("\n")
                        if x.strip()
                    ]

                    evaluation = [
                        x.strip()
                        for x in evaluation_text.split("\n")
                        if x.strip()
                    ]

                    mod.setdefault(
                        "recipes", []
                    ).append(
                        recipe(
                            make_id("recipe"),
                            title,
                            category,
                            objective,
                            ingredients,
                            steps,
                            equipment,
                            safety,
                            evaluation
                        )
                    )

                    st.success(
                        "تم حفظ البطاقة التقنية بنجاح."
                    )

                    st.rerun()


