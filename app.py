                    st.write(item["description"])

                    if st.button(
                        "فتح",
                        key=f"search_open_{index}"
                    ):

                        st.session_state.program_id = item["program_id"]
                        st.session_state.subprogram_id = item["subprogram_id"]

                        if item["subprogram_id"]:
                            st.session_state.page = "program"

                        else:
                            st.session_state.page = "program"

                        st.rerun()


