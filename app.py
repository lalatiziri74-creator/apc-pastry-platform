def calculate_stats():

    programs = st.session_state.data["programs"]

    program_count = len(programs)
    module_count = 0
    lesson_count = 0
    recipe_count = 0

    for program in programs:

        for mod in program.get("modules", []):

            module_count += 1
            lesson_count += len(mod.get("lessons", []))
            recipe_count += len(mod.get("recipes", []))

        for sub in program.get("subPrograms", []):

            for mod in sub.get("modules", []):

                module_count += 1
                lesson_count += len(mod.get("lessons", []))
                recipe_count += len(mod.get("recipes", []))

    return (
        program_count,
        module_count,
        lesson_count,
        recipe_count
    )


def render_stats():

    a, b, c, d = calculate_stats()

    cols = st.columns(4)

    values = [
        ("📚", a, "البرامج"),
        ("📘", b, "الوحدات"),
        ("📝", c, "الدروس"),
        ("🥮", d, "البطاقات التقنية")
    ]

    for col, item in zip(cols, values):

        with col:

            st.markdown(
                f"""
                <div class="stat">
                    <div style="font-size:1.5rem;">{item[0]}</div>
                    <div class="stat-number">{item[1]}</div>
                    <div class="stat-label">{item[2]}</div>
                </div>
                """,
                unsafe_allow_html=True
            )


