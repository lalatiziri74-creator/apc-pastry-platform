def search_platform(query):

    q = query.lower()

    results = []

    for p in st.session_state.data["programs"]:

        if (
            q in p.get("title", "").lower()
            or q in p.get("description", "").lower()
        ):

            results.append({
                "title": p["title"],
                "path": "برنامج رئيسي",
                "description": p["description"]
            })

        for m in p.get("modules", []):

            if (
                q in m.get("title", "").lower()
                or q in m.get("description", "").lower()
            ):

                results.append({
                    "title": m["title"],
                    "path": p["title"],
                    "description": m["description"]
                })

            for lesson in m.get("lessons", []):

                if q in lesson.get("title", "").lower():

                    results.append({
                        "title": lesson["title"],
                        "path": p["title"] + " ← " + m["title"],
                        "description": lesson.get(
                            "content",
                            ""
                        )
                    })

            for card in m.get("cards", []):

                if (
                    q in card.get("title", "").lower()
                    or q in card.get("category", "").lower()
                ):

                    results.append({
                        "title": card["title"],
                        "path": p["title"] + " ← " + m["title"],
                        "description": card.get(
                            "competency",
                            ""
                        )
                    })

        for sp in p.get("subPrograms", []):

            if (
                q in sp.get("title", "").lower()
                or q in sp.get("description", "").lower()
            ):

                results.append({
                    "title": sp["title"],
                    "path": p["title"],
                    "description": sp["description"]
                })

            for m in sp.get("modules", []):

                if (
                    q in m.get("title", "").lower()
                    or q in m.get("description", "").lower()
                ):

                    results.append({
                        "title": m["title"],
                        "path": (
                            p["title"]
                            + " ← "
                            + sp["title"]
                        ),
                        "description": m["description"]
                    })

                for card in m.get("cards", []):

                    if (
                        q in card.get("title", "").lower()
                        or q in card.get("category", "").lower()
                    ):

                        results.append({
                            "title": card["title"],
                            "path": (
                                p["title"]
                                + " ← "
                                + sp["title"]
                                + " ← "
                                + m["title"]
                            ),
                            "description": card.get(
                                "competency",
                                ""
                            )
                        })

    return results


