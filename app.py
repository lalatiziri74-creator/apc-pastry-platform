def render_teacher_panel():

    if not st.session_state.admin:

        st.warning(
            "هذه المساحة مخصصة للأستاذ. أدخل رمز الأستاذ من الشريط الجانبي."
        )

        return

    st.markdown("## 👩‍🏫 لوحة الأستاذ")

    st.markdown(
        """
        <div class="success-box">
        تم تفعيل صلاحيات الأستاذ. يمكنك الآن إضافة الوحدات والدروس
        والبطاقات التقنية والموارد البيداغوجية.
        </div>
        """,
        unsafe_allow_html=True
    )

    tabs = st.tabs(
        [
            "📚 البرامج",
            "➕ إضافة برنامج",
            "📊 التقييم",
            "⚙️ معلومات المنصة"
        ]
    )

    with tabs[0]:

        for program in st.session_state.data["programs"]:

            st.write(
                f"**{program['title']}** — {program.get('hours', 0)} ساعة"
            )

    with tabs[1]:

        with st.form("new_main_program"):

            title = st.text_input(
                "اسم البرنامج الجديد"
            )

            description = st.text_area(
                "وصف البرنامج"
            )

            hours = st.number_input(
                "عدد الساعات",
                min_value=1,
                value=100
            )

            submit = st.form_submit_button(
                "➕ إضافة البرنامج"
            )

            if submit:

                if not title.strip():

                    st.error(
                        "يجب كتابة اسم البرنامج."
                    )

                else:

                    st.session_state.data[
                        "programs"
                    ].append(
                        {
                            "id": make_id("program"),
                            "title": title,
                            "icon": "📚",
                            "type": "main",
                            "hours": hours,
                            "status": "مستحدث",
                            "description": description,
                            "objectives": [],
                            "modules": []
                        }
                    )

                    st.success(
                        "تمت إضافة البرنامج."
                    )

                    st.rerun()

    with tabs[2]:

        st.write(
            "يمكن الوصول إلى التقييم أيضاً من داخل كل برنامج."
        )

    with tabs[3]:

        st.write(
            "اسم المنصة:",
            st.session_state.data["platform"]["name"]
        )

        st.write(
            "المسؤول البيداغوجي:",
            st.session_state.data["platform"]["owner"]
        )


