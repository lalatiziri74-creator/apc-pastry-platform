def add_module_form(parent):

    if not st.session_state.admin:
        return

    with st.expander("➕ إضافة وحدة بيداغوجية جديدة"):

        with st.form(
            "new_module_" + str(parent["id"])
        ):

            title = st.text_input(
                "عنوان الوحدة"
            )

            objective = st.text_area(
                "الهدف والكفاءة المستهدفة"
            )

            submit = st.form_submit_button(
                "حفظ الوحدة"
            )

            if submit:

                if not title.strip():

                    st.error("يجب إدخال عنوان الوحدة.")

                else:

                    parent.setdefault(
                        "modules", []
                    ).append(
                        module(
                            make_id("module"),
                            title,
                            objective,
                            [],
                            []
                        )
                    )

                    st.success(
                        "تمت إضافة الوحدة بنجاح."
                    )

                    st.rerun()


