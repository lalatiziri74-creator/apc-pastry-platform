def recipe(rid, title, category, objective, ingredients, steps, equipment, safety, evaluation):
    return {
        "id": rid,
        "title": title,
        "category": category,
        "objective": objective,
        "ingredients": ingredients,
        "steps": steps,
        "equipment": equipment,
        "safety": safety,
        "evaluation": evaluation
    }


def lesson(lid, title, objective, content, activities):
    return {
        "id": lid,
        "title": title,
        "objective": objective,
        "content": content,
        "activities": activities
    }


def module(mid, title, objective, lessons, recipes=None):
    return {
        "id": mid,
        "title": title,
        "objective": objective,
        "lessons": lessons,
        "recipes": recipes or []
    }


def make_id(prefix: str) -> str:
    return prefix + "_" + datetime.now().strftime("%Y%m%d%H%M%S%f")


