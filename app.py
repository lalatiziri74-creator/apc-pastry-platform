def breadcrumb():

    parts = ["🏠 الرئيسية"]

    if st.session_state.program_id:

        p = get_program(st.session_state.program_id)

        if p:
            parts.append(p["title"])

    if st.session_state.subprogram_id:

        sp = get_subprogram(
            st.session_state.program_id,
            st.session_state.subprogram_id
        )

        if sp:
            parts.append(sp["title"])

    if st.session_state.module_id:

        container = (
            sp
            if st.session_state.subprogram_id
            else p
        )

        if container:

            m = get_module(
                container,
                st.session_state.module_id
            )

            if m:
                parts.append(m["title"])

    st.markdown(
        " &nbsp; ← &nbsp; ".join(
            [html.escape(str(x)) for x in parts]
        )
    )


