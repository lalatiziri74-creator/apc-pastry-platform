            st.markdown("### 📚 الوحدة الثانية: تقنيات الحشو والتزيين المعاصر للحلويات التقليدية")
            st.info("الحجم الساعي المقترح: 40 ساعة (تطبيقي مكثف)")
            st.markdown("""
            * **الهدف البيداغوجي:** إتقان تقنيات الحشو الداخلي (المكسرات، العقاش، العسل) وطرق التزيين بالطلية والتلميع.
            * **الدرس الأول:** معايير تحضير الحشوات الحساسة وضمان مدة صلاحيتها.
            * **الدرس الثاني:** تقنيات الطلاء الملكي (الطلية) وضمان الاستواء واللمعان دون فقاعات هوائية.
            * **البطاقة التقنية المرفقة:** بطاقة تقنية لإعداد وتشكيل الحلويات المعسلة والطلية مع معايير ضبط درجات الحرارة.
            """)
            
