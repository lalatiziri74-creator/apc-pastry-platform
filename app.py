def platform_stats():

    programs = st.session_state.data.get("programs", [])

    subprograms = 0
    modules = 0
    lessons = 0
    cards = 0

    for p in programs:

        for m in p.get("modules", []):

            modules += 1
            lessons += len(m.get("lessons", []))
            cards += len(m.get("cards", []))

        for sp in p.get("subPrograms", []):

            subprograms += 1

            for m in sp.get("modules", []):

                modules += 1
                lessons += len(m.get("lessons", []))
                cards += len(m.get("cards", []))

    return {
        "programs": len(programs),
        "subprograms": subprograms,
        "modules": modules,
        "lessons": lessons,
        "cards": cards
    }


