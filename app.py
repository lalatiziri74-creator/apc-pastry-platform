def admin_add_recipe_form(module_obj):
    if not st.session_state.admin:
        return
    with st.expander("➕ إضافة بطاقة تقنية جديدة", expanded=False):
        with st.form(f"add_recipe_{module_obj['id']}"):
            title = st.text_input("اسم الوصفة")
            category = st.text_input("التصنيف")
            objective = st.text_area("الهدف المهني")
            ingredients_text = st.text_area("المقادير (كل سطر: اسم | كمية | وحدة)")
            steps_text = st.text_area("مراحل الإنجاز (كل مرحلة في سطر)")
            equipment_text = st.text_area("العتاد (كل أداة في سطر)")
            safety_text = st.text_area("قواعد السلامة (كل قاعدة في سطر)")
            evaluation_text = st.text_area("معايير التقييم (كل معيار في سطر)")
            submitted = st.form_submit_button("حفظ البطاقة")
            if submitted:
                if not title.strip():
                    st.error("أدخل اسم الوصفة.")
                else:
                    ingredients = []
                    errors = []
                    for line in ingredients_text.split("\n"):
                        if not line.strip():
                            continue
                        parts = [x.strip() for x in line.split("|")]
                        if len(parts) == 3:
                            try:
                                amt = float(parts[1])
                                ingredients.append((parts[0], amt, parts[2]))
                            except ValueError:
                                errors.append(f"الكمية غير صحيحة في السطر: '{line}'")
                        else:
                            errors.append(f"الصيغة غير صحيحة في السطر: '{line}' (يجب: اسم | كمية | وحدة)")

                    if errors:
                        st.error("❌ أخطاء في إدخال المقادير:")
                        for err in errors:
                            st.write(f"- {err}")
                        return

                    steps = [s.strip() for s in steps_text.split("\n") if s.strip()]
                    equipment = [e.strip() for e in equipment_text.split("\n") if e.strip()]
                    safety = [s.strip() for s in safety_text.split("\n") if s.strip()]
                    evaluation = [e.strip() for e in evaluation_text.split("\n") if e.strip()]

                    module_obj.setdefault("recipes", []).append(
                        recipe(make_id("recipe"), title, category, objective, ingredients, steps, equipment, safety, evaluation)
                    )
                    st.success("تم حفظ البطاقة التقنية.")
                    st.rerun()


