def add_lesson_form(mod):

    if not st.session_state.admin:
        return

    with st.expander(
        "➕ إضافة درس إلى هذه الوحدة"
    ):

        with st.form(
            "new_lesson_" + str(mod["id"])
        ):

            title = st.text_input(
                "عنوان الدرس"
            )

            objective = st.text_area(
                "الهدف"
            )

            content = st.text_area(
                "محتوى الدرس"
            )

            activities_text = st.text_area(
                "النشاطات التطبيقية — كل نشاط في سطر"
            )

            submit = st.form_submit_button(
                "حفظ الدرس"
            )

            if submit:

                if not title.strip():

                    st.error(
                        "أدخل عنوان الدرس."
                    )

                else:

                    activities = [
                        x.strip()
                        for x in activities_text.split("\n")
                        if x.strip()
                    ]

                    mod.setdefault(
                        "lessons", []
                    ).append(
                        lesson(
                            make_id("lesson"),
                            title,
                            objective,
                            content,
                            activities
                        )
                    )

                    st.success(
                        "تمت إضافة الدرس."
                    )

                    st.rerun()


