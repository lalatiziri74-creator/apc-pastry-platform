def render_recipe(rec):

    st.markdown(
        f"""
        <div class="recipe-box">

            <h3>
            🥮 {html.escape(rec["title"])}
            </h3>

            <span class="badge">
            {html.escape(rec["category"])}
            </span>

            <p>
            <strong>🎯 الهدف:</strong>
            {html.escape(rec["objective"])}
            </p>

        </div>
        """,
        unsafe_allow_html=True
    )

    col1, col2 = st.columns(2)

    with col1:

        st.markdown("### 🧺 المقادير")

        for name, amount, unit in rec["ingredients"]:

            st.write(
                f"• **{name}** — {amount} {unit}"
            )

    with col2:

        st.markdown("### 🛠️ العتاد")

        for item in rec["equipment"]:
            st.write("• " + item)

    st.markdown("### 👩‍🍳 مراحل الإنجاز")

    for index, step in enumerate(rec["steps"], 1):

        st.markdown(
            f"**{index}.** {step}"
        )

    st.markdown("### 🧼 قواعد النظافة والسلامة")

    for rule in rec["safety"]:
        st.write("• " + rule)

    st.markdown("### 📊 معايير التقييم")

    for criterion in rec["evaluation"]:
        st.write("• " + criterion)


