def get_program(pid):

    for p in st.session_state.data["programs"]:
        if p["id"] == pid:
            return p

    return None


def get_subprogram(pid, sid):

    p = get_program(pid)

    if not p:
        return None

    for sp in p.get("subPrograms", []):
        if sp["id"] == sid:
            return sp

    return None


def get_module(container, mid):

    for m in container.get("modules", []):
        if m["id"] == mid:
            return m

    return None


def get_card(container, cid):

    for m in container.get("modules", []):

        for c in m.get("cards", []):

            if c["id"] == cid:
                return c

    return None


def generate_id(prefix="id"):

    return (
        prefix
        + "_"
        + datetime.now().strftime("%Y%m%d%H%M%S%f")
    )


